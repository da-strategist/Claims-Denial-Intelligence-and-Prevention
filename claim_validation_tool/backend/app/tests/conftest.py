def _write_users(path: Path) -> None:
    now = datetime.now(UTC).isoformat()
    users = [
        {
            "username": username,
            "display_name": f"Test {role}",
            "role": role,
            "password_hash": _TEST_HASH,
            "active": True,
            "created_at": now,
            "password_changed_at": now,
            "organisation_id": org,
        }
        for org, names in (("meridian", USERNAMES), ("lakeside", LAKESIDE_USERNAMES))
        for role, username in names.items()
    ] + [
        {
            "username": PLATFORM_USERNAME,
            "display_name": "Test platform",
            "role": "platform",
            "password_hash": _TEST_HASH,
            "active": True,
            "created_at": now,
            "password_changed_at": now,
        }
    ]
    path.write_text(json.dumps({"users": users}))


def _write_orgs(root: Path) -> None:
    now = datetime.now(UTC).isoformat()
    root.mkdir(parents=True, exist_ok=True)
    orgs = [
        {"id": org, "name": org.title(), "data_dir": str(data_dir), "status": "active", "created_at": now}
        for org, data_dir in ORGS.items()
    ]
    (root / "organisations.json").write_text(json.dumps({"organisations": orgs}))


def api_routes():
    """(method, path) for every /api route, including those in included routers.

    FastAPI wraps each included router, so the app's own route list holds wrappers, not
    the routes; walk into them (a flat walk silently finds nothing).
    """
    from fastapi.routing import APIRoute

    def walk(routes):
        for route in routes:
            if isinstance(route, APIRoute):
                yield route
            elif hasattr(route, "original_router"):
                yield from walk(route.original_router.routes)
            elif hasattr(route, "routes"):
                yield from walk(route.routes)

    for route in walk(app.routes):
        if route.path.startswith("/api/"):
            for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
                yield method, route.path


def use_data_dir(org: str, data_dir: Path) -> None:
    """Point an organisation at other claims CSVs (e.g. a modified copy of the fixtures)."""
    registry = get_org_registry()
    path = registry.root / "organisations.json"
    data = json.loads(path.read_text())
    for item in data["organisations"]:
        if item["id"] == org:
            item["data_dir"] = str(data_dir)
    path.write_text(json.dumps(data))
    get_org_registry.cache_clear()
    get_repository.cache_clear()


def org_folder(org: str = "meridian") -> Path:
    """The organisation's app-data folder in this test's temporary orgs directory."""
    return get_org_registry().folder(org)


def sign_in(client: TestClient, role: Role, org: str = "meridian") -> TestClient:
    """Give the client a session as the test user with `role` in `org` (skips the slow
    password check)."""
    if role == Role.PLATFORM:
        username = PLATFORM_USERNAME
    else:
        username = (USERNAMES if org == "meridian" else LAKESIDE_USERNAMES)[role]
    token = get_session_store().create(username)
    client.cookies.set(SESSION_COOKIE, token)
    return client


